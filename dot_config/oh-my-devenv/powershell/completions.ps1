function Get-PowerShellCompletionDirectory {
    param([Parameter(Mandatory)][string]$LocalData)

    $directory = $LocalData
    foreach ($segment in 'oh-my-devenv', 'completions', 'powershell') {
        $directory = Join-Path $directory $segment
        $item = Get-Item -LiteralPath $directory -Force -ErrorAction SilentlyContinue
        if ($item -and (-not $item.PSIsContainer -or ($item.Attributes -band [IO.FileAttributes]::ReparsePoint))) {
            throw "Expected a regular completion directory at '$directory'."
        }
    }
    $directory
}

function Test-OwnedPowerShellCompletion {
    param([string]$Path)

    $file = Get-Item -LiteralPath $Path -Force -ErrorAction SilentlyContinue
    $file -and -not $file.PSIsContainer -and -not ($file.Attributes -band [IO.FileAttributes]::ReparsePoint) -and
        (Get-Content -LiteralPath $Path -TotalCount 1) -ceq '# oh-my-devenv: generated by install-shell-completions.ps1'
}

function Get-OwnedPowerShellCompletion {
    param([Parameter(Mandatory)][string]$Directory)

    if (Test-Path -LiteralPath $Directory -PathType Container) {
        Get-ChildItem -LiteralPath $Directory -File -Force -Filter '*.ps1' |
            Where-Object { $_.Name -cmatch '^[A-Za-z0-9][A-Za-z0-9_.+-]*\.ps1$' -and
                (Test-OwnedPowerShellCompletion -Path $_.FullName) }
    }
}

function Import-OwnedPowerShellCompletion {
    param([Parameter(Mandatory)][string]$LocalData)

    $ErrorActionPreference = 'Stop'
    $directory = Get-PowerShellCompletionDirectory -LocalData $LocalData
    foreach ($completion in Get-OwnedPowerShellCompletion -Directory $directory) {
        . $completion.FullName
    }
}
