[Diagnostics.CodeAnalysis.SuppressMessageAttribute('PSUseDeclaredVarsMoreThanAssignments', '',
    Justification = 'Pester shares BeforeEach variables with the individual tests.')]
param()

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

BeforeAll {
    $helpers = Join-Path $PSScriptRoot '..'
    $profileSource = Join-Path $helpers '../../dot_config/oh-my-devenv/powershell'
    . (Join-Path $helpers 'common.ps1')
    . (Join-Path $helpers 'completions.ps1')
}

Describe 'PowerShell completion lifecycle' {
    BeforeEach {
        $localData = [IO.Directory]::CreateTempSubdirectory('oh-my-devenv-completion-').FullName
        $manifest = Join-Path $localData 'completion manifest.txt'
        $directory = Get-PowerShellCompletionDirectory -LocalData $localData
        [void][IO.Directory]::CreateDirectory($directory)
        $options = @{ ManifestPath = $manifest; LocalData = $localData }
        $marker = '# oh-my-devenv: generated by install-shell-completions.ps1'
        Set-Content -LiteralPath $manifest -Value @('# shared inventory shape', 'fixture-generated # inline', 'fixture-shipped', 'fixture-absent')
        Mock Get-PathApplication { @{ Source = $Name } }
        Mock Get-PathApplication { $null } -ParameterFilter { $Name -in 'fixture-absent', 'fixture-unsupported-absent' }
        Mock Get-PowerShellCompletionArgument { 'fixture-completion'; 'powershell' } -ParameterFilter {
            $Name -in 'fixture-generated', 'fixture-shipped', 'fixture-absent'
        }

        $generated = Join-Path $directory 'fixture-generated.ps1'
        $shippedTarget = Join-Path $directory 'fixture-shipped.ps1'
        $shipped = Join-Path $localData 'PowerShell/completions/fixture-shipped.ps1'
        [void][IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($shipped))
        [IO.File]::WriteAllText($shipped, '# shipped completion')
        $stale = Join-Path $directory 'fixture-removed.ps1'
        $unowned = Join-Path $directory 'fixture-user.ps1'
        [IO.File]::WriteAllText($stale, "$marker`n# obsolete")
        [IO.File]::WriteAllBytes($unowned, [byte[]](0xef, 0xbb, 0xbf, 35, 13, 10))
    }

    AfterEach {
        [IO.Directory]::Delete($localData, $true)
    }

    It 'prefers a shipped asset, skips absent known tools, and prunes only obsolete owned files' {
        Mock Invoke-NativeCommand {
            if (($Arguments -join ' ') -cne 'fixture-completion powershell') { throw 'Wrong generator arguments.' }
            @{ Stdout = "`n# generated completion"; ExitCode = 0 }
        } -ParameterFilter { $Executable -eq 'fixture-generated' }
        Mock Invoke-NativeCommand { throw "Unexpected generator '$Executable'." } -ParameterFilter {
            $Executable -ne 'fixture-generated'
        }
        $userBytes = [IO.File]::ReadAllBytes($unowned)
        $shippedBytes = [IO.File]::ReadAllBytes($shipped)
        $log = Invoke-PowerShellCompletion @options -Action install 6>&1 | Out-String
        $log | Should -Match 'fixture-absent.*not on PATH'
        Should -Invoke Invoke-NativeCommand -Times 1 -Exactly
        [IO.File]::ReadAllText($generated) | Should -BeExactly "$marker`n# generated completion"
        [IO.File]::ReadAllText($shippedTarget) | Should -BeExactly "$marker`n# shipped completion"
        [Linq.Enumerable]::SequenceEqual[byte]([IO.File]::ReadAllBytes($shipped), $shippedBytes) | Should -BeTrue
        [Linq.Enumerable]::SequenceEqual[byte]([IO.File]::ReadAllBytes($unowned), $userBytes) | Should -BeTrue
        [IO.File]::Exists($stale) | Should -BeFalse
        @(Invoke-PowerShellCompletion @options -Action list) | Should -Be @($generated, $shippedTarget)
        { Invoke-PowerShellCompletion @options -Action check } | Should -Not -Throw
        Should -Invoke Invoke-NativeCommand -Times 1 -Exactly
    }

    It 'rejects an unknown command in <Action> even when <Name> is absent or has a shipped asset' -ForEach @(
        @{ Action = 'install'; Name = 'fixture-unsupported' }
        @{ Action = 'check'; Name = 'fixture-unsupported' }
        @{ Action = 'install'; Name = 'fixture-unsupported-absent' }
        @{ Action = 'check'; Name = 'fixture-unsupported-absent' }
    ) {
        Set-Content -LiteralPath $manifest -Value $Name
        [IO.File]::WriteAllText((Join-Path $localData "PowerShell/completions/$Name.ps1"), '# unsupported completion')
        { Invoke-PowerShellCompletion @options -Action $Action } | Should -Throw "*Unsupported completion generator*'$Name'*"
        [IO.File]::Exists($stale) | Should -BeTrue
        [IO.File]::Exists((Join-Path $directory "$Name.ps1")) | Should -BeFalse
    }

    It 'lists obsolete owned files and reports missing and obsolete files in check' {
        @(Invoke-PowerShellCompletion @options -Action list) | Should -Be @($stale)
        { Invoke-PowerShellCompletion @options -Action check } |
            Should -Throw "*missing*fixture-generated.ps1*stale*fixture-removed.ps1*"
    }

    It 'leaves an unowned target byte-for-byte intact' {
        [IO.File]::Copy($unowned, $generated)
        Mock Invoke-NativeCommand { throw 'Unexpected generator' }
        { Invoke-PowerShellCompletion @options -Action install } | Should -Throw '*Refusing to overwrite unowned PowerShell completion*'
        [Linq.Enumerable]::SequenceEqual[byte]([IO.File]::ReadAllBytes($unowned), [IO.File]::ReadAllBytes($generated)) | Should -BeTrue
        Should -Invoke Invoke-NativeCommand -Times 0 -Exactly
    }

    It 'preserves a previous completion when its generator fails' {
        [IO.File]::WriteAllText($generated, "$marker`n# previous")
        $before = [IO.File]::ReadAllBytes($generated)
        Mock Invoke-NativeCommand { throw 'Generator exited with code 42.' }
        { Invoke-PowerShellCompletion @options -Action install } | Should -Throw '*Generator exited with code 42*'
        [Linq.Enumerable]::SequenceEqual[byte]([IO.File]::ReadAllBytes($generated), $before) | Should -BeTrue
        [IO.File]::Exists($stale) | Should -BeTrue
    }

    It 'rejects invalid generated PowerShell without replacing the old script' {
        [IO.File]::WriteAllText($generated, "$marker`n# previous")
        $before = [IO.File]::ReadAllBytes($generated)
        Mock Invoke-NativeCommand { @{ Stdout = 'function {'; ExitCode = 0 } }
        { Invoke-PowerShellCompletion @options -Action install } | Should -Throw '*Invalid PowerShell completion*'
        [Linq.Enumerable]::SequenceEqual[byte]([IO.File]::ReadAllBytes($generated), $before) | Should -BeTrue
    }

    It 'rejects malformed and duplicate manifest entries before touching the target' -ForEach @(
        @{ Lines = @('one two'); Diagnostic = 'Invalid completion command name' }
        @{ Lines = @('one', 'ONE'); Diagnostic = 'Duplicate completion command' }
    ) {
        Set-Content -LiteralPath $manifest -Value $Lines
        { Invoke-PowerShellCompletion @options -Action install } | Should -Throw "*$Diagnostic*"
        [IO.File]::Exists($stale) | Should -BeTrue
    }

    It 'loads only marked regular scripts' {
        [IO.File]::WriteAllText($unowned, 'throw "Loaded an unowned script"')
        [IO.File]::WriteAllText($stale, "$marker`n" + '$env:OH_MY_DEVENV_COMPLETION_FIXTURE = "loaded"')
        try {
            Import-OwnedPowerShellCompletion -LocalData $localData
            $env:OH_MY_DEVENV_COMPLETION_FIXTURE | Should -BeExactly 'loaded'
        } finally {
            $env:OH_MY_DEVENV_COMPLETION_FIXTURE = $null
        }
    }

    It 'loads marked scripts in a redirected profile only with the explicit probe' {
        Copy-Item -LiteralPath (Join-Path $profileSource 'profile.ps1'), (Join-Path $profileSource 'completions.ps1') `
            -Destination $localData
        [IO.File]::WriteAllText((Join-Path $localData 'environment.ps1'), @'
function Get-ManagedProfilePathEntry { $PSScriptRoot }
function Get-PathApplication { param([string]$Name, [switch]$Optional) }
function ConvertTo-PathKey { param([string]$Path) $Path }
'@)
        [IO.File]::WriteAllText((Join-Path $localData 'probe.ps1'), @'
$ErrorActionPreference = 'Stop'
if (-not [Console]::IsOutputRedirected) { throw 'Expected redirected output.' }
. (Join-Path $PSScriptRoot 'profile.ps1')
[Console]::WriteLine($env:OH_MY_DEVENV_COMPLETION_FIXTURE)
'@)
        [IO.File]::WriteAllText($stale, "$marker`n" + '$env:OH_MY_DEVENV_COMPLETION_FIXTURE = "loaded"')
        $pwsh = Join-Path $PSHOME $(if ($IsWindows) { 'pwsh.exe' } else { 'pwsh' })
        $arguments = @('-NoProfile', '-File', (Join-Path $localData 'probe.ps1'))
        $environment = @{
            GOBIN = $localData
            OH_MY_DEVENV_COMPLETION_FIXTURE = $null
            OH_MY_DEVENV_PROBE_COMPLETION_LOCAL_DATA = $localData
            OH_MY_DEVENV_PROBE_PROMPT = $null
        }
        $probe = @{ Executable = $pwsh; Arguments = $arguments; Environment = $environment; WorkingDirectory = $localData; TimeoutSeconds = 30 }
        (Invoke-NativeCommand @probe).Stdout.Trim() | Should -BeNullOrEmpty
        $environment.OH_MY_DEVENV_PROBE_PROMPT = '1'
        (Invoke-NativeCommand @probe).Stdout.Trim() | Should -BeExactly 'loaded'
    }
}
